//! Background hook threads (each with its own Win32 message loop).
//!
//! - Keyboard (WH_KEYBOARD_LL): only for Quick Accent (M8) and Esc while picking a
//!   colour. The filter decides synchronously whether to swallow a key and **never
//!   records anything** (spec §3.2: no keylogging).
//! - Mouse (WH_MOUSE_LL): swallows clicks only while `capture` is set (colour picker).
//! - Clipboard (AddClipboardFormatListener on a message-only window): M7.
//! - Foreground (SetWinEventHook EVENT_SYSTEM_FOREGROUND): M4 — no keyboard hook.

use std::cell::RefCell;
use std::sync::Arc;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::mpsc::{Receiver, Sender, channel};
use std::thread::JoinHandle;

use windows::Win32::Foundation::{HWND, LPARAM, LRESULT, WPARAM};
use windows::Win32::System::DataExchange::{AddClipboardFormatListener, RemoveClipboardFormatListener};
use windows::Win32::System::LibraryLoader::GetModuleHandleW;
use windows::Win32::System::Threading::GetCurrentThreadId;
use windows::Win32::UI::Accessibility::{HWINEVENTHOOK, SetWinEventHook, UnhookWinEvent};
use windows::Win32::UI::WindowsAndMessaging::{
    CallNextHookEx, CreateWindowExW, DefWindowProcW, DestroyWindow, DispatchMessageW, EVENT_SYSTEM_FOREGROUND,
    GetMessageW, HC_ACTION, HHOOK, HWND_MESSAGE, KBDLLHOOKSTRUCT, LLKHF_INJECTED, MSG, MSLLHOOKSTRUCT,
    PostThreadMessageW, RegisterClassW, SetWindowsHookExW, TranslateMessage, UnhookWindowsHookEx, WH_KEYBOARD_LL,
    WH_MOUSE_LL, WINDOW_EX_STYLE, WINDOW_STYLE, WINEVENT_OUTOFCONTEXT, WM_CLIPBOARDUPDATE, WM_KEYDOWN, WM_KEYUP,
    WM_LBUTTONDOWN, WM_LBUTTONUP, WM_QUIT, WM_RBUTTONDOWN, WM_RBUTTONUP, WM_SYSKEYDOWN, WM_SYSKEYUP, WNDCLASSW,
};
use windows::core::w;

/// A key transition seen by the keyboard filter.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct KeyEvent {
    pub vk: u32,
    pub down: bool,
    /// Generated by SendInput (ours or another app's) — filters should ignore these.
    pub injected: bool,
}

/// Returns `true` to swallow the key.
pub type KeyFilter = Box<dyn FnMut(KeyEvent) -> bool + Send>;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum MouseEvent {
    LeftDown { x: i32, y: i32 },
    RightDown { x: i32, y: i32 },
}

/// A running hook thread; dropping it unhooks and stops the thread.
pub struct HookThread {
    thread_id: u32,
    join: Option<JoinHandle<()>>,
}

impl Drop for HookThread {
    fn drop(&mut self) {
        unsafe {
            let _ = PostThreadMessageW(self.thread_id, WM_QUIT, WPARAM(0), LPARAM(0));
        }
        if let Some(j) = self.join.take() {
            let _ = j.join();
        }
    }
}

fn spawn(name: &str, setup: impl FnOnce() -> Box<dyn FnOnce()> + Send + 'static) -> HookThread {
    let (tx, rx) = channel::<u32>();
    let join = std::thread::Builder::new()
        .name(name.into())
        .spawn(move || {
            let teardown = setup();
            let _ = tx.send(unsafe { GetCurrentThreadId() });
            let mut msg = MSG::default();
            unsafe {
                while GetMessageW(&mut msg, None, 0, 0).as_bool() {
                    let _ = TranslateMessage(&msg);
                    DispatchMessageW(&msg);
                }
            }
            teardown();
        })
        .expect("spawn hook thread");
    let thread_id = rx.recv().unwrap_or(0);
    HookThread { thread_id, join: Some(join) }
}

// ── Keyboard ────────────────────────────────────────────────────────────────

thread_local! {
    static KEY_FILTER: RefCell<Option<KeyFilter>> = const { RefCell::new(None) };
    static MOUSE: RefCell<Option<(Arc<AtomicBool>, Sender<MouseEvent>)>> = const { RefCell::new(None) };
    static CLIP: RefCell<Option<Sender<()>>> = const { RefCell::new(None) };
    static FG: RefCell<Option<Sender<isize>>> = const { RefCell::new(None) };
}

unsafe extern "system" fn keyboard_proc(code: i32, wparam: WPARAM, lparam: LPARAM) -> LRESULT {
    if code == HC_ACTION as i32 {
        let k = unsafe { &*(lparam.0 as *const KBDLLHOOKSTRUCT) };
        let msg = wparam.0 as u32;
        let down = msg == WM_KEYDOWN || msg == WM_SYSKEYDOWN;
        let up = msg == WM_KEYUP || msg == WM_SYSKEYUP;
        if down || up {
            let ev = KeyEvent { vk: k.vkCode, down, injected: k.flags.0 & LLKHF_INJECTED.0 != 0 };
            let swallow = KEY_FILTER.with(|f| f.borrow_mut().as_mut().map(|f| f(ev)).unwrap_or(false));
            if swallow {
                return LRESULT(1);
            }
        }
    }
    unsafe { CallNextHookEx(None, code, wparam, lparam) }
}

/// Install a low-level keyboard hook running `filter` on its own thread.
pub fn keyboard(filter: KeyFilter) -> HookThread {
    spawn("halo-kbd-hook", move || {
        KEY_FILTER.with(|f| *f.borrow_mut() = Some(filter));
        let hook = unsafe {
            SetWindowsHookExW(WH_KEYBOARD_LL, Some(keyboard_proc), GetModuleHandleW(None).ok().map(|m| m.into()), 0)
        };
        Box::new(move || {
            if let Ok(h) = hook {
                let _ = unsafe { UnhookWindowsHookEx(h) };
            }
        })
    })
}

// ── Mouse ───────────────────────────────────────────────────────────────────

unsafe extern "system" fn mouse_proc(code: i32, wparam: WPARAM, lparam: LPARAM) -> LRESULT {
    if code == HC_ACTION as i32 {
        let m = unsafe { &*(lparam.0 as *const MSLLHOOKSTRUCT) };
        let msg = wparam.0 as u32;
        let swallow = MOUSE.with(|s| {
            let s = s.borrow();
            let Some((capture, tx)) = s.as_ref() else { return false };
            if !capture.load(Ordering::Relaxed) {
                return false;
            }
            match msg {
                WM_LBUTTONDOWN => {
                    let _ = tx.send(MouseEvent::LeftDown { x: m.pt.x, y: m.pt.y });
                    true
                }
                WM_RBUTTONDOWN => {
                    let _ = tx.send(MouseEvent::RightDown { x: m.pt.x, y: m.pt.y });
                    true
                }
                WM_LBUTTONUP | WM_RBUTTONUP => true,
                _ => false,
            }
        });
        if swallow {
            return LRESULT(1);
        }
    }
    unsafe { CallNextHookEx(None, code, wparam, lparam) }
}

/// Low-level mouse hook; clicks are reported and swallowed only while `capture` is true.
pub fn mouse(capture: Arc<AtomicBool>) -> (HookThread, Receiver<MouseEvent>) {
    let (tx, rx) = channel();
    let t = spawn("halo-mouse-hook", move || {
        MOUSE.with(|s| *s.borrow_mut() = Some((capture, tx)));
        let hook: windows::core::Result<HHOOK> = unsafe {
            SetWindowsHookExW(WH_MOUSE_LL, Some(mouse_proc), GetModuleHandleW(None).ok().map(|m| m.into()), 0)
        };
        Box::new(move || {
            if let Ok(h) = hook {
                let _ = unsafe { UnhookWindowsHookEx(h) };
            }
        })
    });
    (t, rx)
}

// ── Clipboard ───────────────────────────────────────────────────────────────

unsafe extern "system" fn clip_wndproc(hwnd: HWND, msg: u32, wp: WPARAM, lp: LPARAM) -> LRESULT {
    if msg == WM_CLIPBOARDUPDATE {
        CLIP.with(|c| {
            if let Some(tx) = c.borrow().as_ref() {
                let _ = tx.send(());
            }
        });
        return LRESULT(0);
    }
    unsafe { DefWindowProcW(hwnd, msg, wp, lp) }
}

/// Notifies on every clipboard change (content is read by the caller).
pub fn clipboard() -> (HookThread, Receiver<()>) {
    let (tx, rx) = channel();
    let t = spawn("halo-clipboard", move || {
        CLIP.with(|c| *c.borrow_mut() = Some(tx));
        let hwnd = unsafe {
            let class = w!("HaloClipboardListener");
            let wc = WNDCLASSW {
                lpfnWndProc: Some(clip_wndproc),
                hInstance: GetModuleHandleW(None).map(|m| m.into()).unwrap_or_default(),
                lpszClassName: class,
                ..Default::default()
            };
            RegisterClassW(&wc);
            CreateWindowExW(
                WINDOW_EX_STYLE(0),
                class,
                w!(""),
                WINDOW_STYLE(0),
                0,
                0,
                0,
                0,
                Some(HWND_MESSAGE),
                None,
                None,
                None,
            )
        };
        if let Ok(h) = hwnd {
            let _ = unsafe { AddClipboardFormatListener(h) };
        }
        Box::new(move || {
            if let Ok(h) = hwnd {
                unsafe {
                    let _ = RemoveClipboardFormatListener(h);
                    let _ = DestroyWindow(h);
                }
            }
        })
    });
    (t, rx)
}

// ── Foreground window ───────────────────────────────────────────────────────

unsafe extern "system" fn fg_proc(
    _hook: HWINEVENTHOOK,
    _event: u32,
    hwnd: HWND,
    _idobject: i32,
    _idchild: i32,
    _thread: u32,
    _time: u32,
) {
    FG.with(|f| {
        if let Some(tx) = f.borrow().as_ref() {
            let _ = tx.send(hwnd.0 as isize);
        }
    });
}

/// Reports the new foreground window handle on every focus change.
pub fn foreground() -> (HookThread, Receiver<isize>) {
    let (tx, rx) = channel();
    let t = spawn("halo-foreground", move || {
        FG.with(|f| *f.borrow_mut() = Some(tx));
        let hook = unsafe {
            SetWinEventHook(
                EVENT_SYSTEM_FOREGROUND,
                EVENT_SYSTEM_FOREGROUND,
                None,
                Some(fg_proc),
                0,
                0,
                WINEVENT_OUTOFCONTEXT,
            )
        };
        Box::new(move || {
            if !hook.is_invalid() {
                let _ = unsafe { UnhookWinEvent(hook) };
            }
        })
    });
    (t, rx)
}
